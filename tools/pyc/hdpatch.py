def read_hd_cfg():
    """Читает hd.cfg: список (W, H, BPP, F); первая строка - стартовое разрешение."""
    rows = []
    for line in open(CFG_PATH, encoding='utf-8'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        p = line.split()
        if len(p) != 4:
            raise Exception('hd.cfg: строка "%s" - не 4 поля (W H BPP F)' % line)
        rows.append((int(p[0]), int(p[1]), int(p[2]), int(p[3])))
    if not rows:
        raise Exception('hd.cfg: пустой список разрешений')
    return rows


def hd_res_src(rows):
    # модуль-конфиг: ROWS - фолбэк из hd.cfg на момент сборки; Read() читает
    # hd.cfg текстом в рантайме игры, поэтому смена разрешения не требует компиляции.
    # Prepare(): при старте сам выбирает текстуру меню по aspect ratio -
    # 16:9 (ratio >= 1.6) -> mm_bkg01_169.btf, иначе оригинал mm_bkg01_43.btf;
    # кладёт выбранную в data/textures/mm_bkg01.btf (движок грузит по неизменному имени).
    lines = ['# HD-cfg (generated by hdpatch.py from hd.cfg); ROWS = fallback',
             'ROWS = ' + repr([tuple(r) for r in rows]),
             '',
             'def Read():',
             "    try:",
             "        f = open('hd.cfg')",
             "        s = f.read()",
             "        f.close()",
             "        out = []",
             "        for line in s.split(chr(10)):",
             "            line = line.strip()",
             "            if not line:",
             "                continue",
             "            if line[0] == '#':",
             "                continue",
             "            p = line.split()",
             "            if len(p) < 4:",
             "                continue",
             "            out.append((int(p[0]), int(p[1]), int(p[2]), int(p[3])))",
             "        if out:",
             "            return out[0]",
             "    except:",
             "        pass",
             "    return ROWS[0]",
             '',
             'def Prepare():',
             "    w, h, bpp, f = Read()",
             "    wide = h > 0 and float(w) / float(h) >= 1.6",
             "    src = 'data/textures/mm_bkg01_43.btf'",
             "    if wide:",
             "        src = 'data/textures/mm_bkg01_169.btf'",
             "    # временный чёрный фон для измерений UI: флаг blackbg.flag в корне игры",
             "    try:",
             "        g = open('blackbg.flag')",
             "        g.close()",
             "        src = 'data/textures/mm_bkg01_black_43.btf'",
             "        if wide:",
             "            src = 'data/textures/mm_bkg01_black_169.btf'",
             "    except:",
             "        pass",
             "    try:",
             "        d = open(src, 'rb')",
             "        px = d.read()",
             "        d.close()",
             "        t = open('data/textures/mm_bkg01.btf', 'wb')",
             "        t.write(px)",
             "        t.close()",
             "    except:",
             "        pass",
              "    # шрифты: лист+таблица ВСЕГДА парой. 16:9 (k=0.75) - сжатые по X листы",
             "    # *_169; прочие соотношения (в т.ч. 4:3) - родные *_43 -> побитово оригинал.",
             "    f169 = h > 0 and abs(float(w) / float(h) - 16.0 / 9.0) <= 0.06",
             "    sfx = '_43'",
             "    if f169:",
             "        sfx = '_169'",
             "    for nm in ('ld_uncial12', 'ld_uncial20', 'ld_tahoma11', 'ld_numbers15'):",
             "        try:",
             "            d = open('data/textures/' + nm + sfx + '.btf', 'rb')",
             "            px = d.read()",
             "            d.close()",
             "            t = open('data/textures/' + nm + '.btf', 'wb')",
             "            t.write(px)",
             "            t.close()",
             "            d = open('data/fonts/' + nm + sfx + '.fdf', 'rb')",
             "            px = d.read()",
             "            d.close()",
             "            t = open('data/fonts/' + nm + '.fdf', 'wb')",
             "            t.write(px)",
             "            t.close()",
             "        except:",
             "            pass",
             "    return",
             '']
    return chr(10).join(lines)


def gs_new():
    # gamescript.Initialize: разрешение читается из hd.cfg в рантайме, затем масштаб
    lines = ['def Initialize():',
             '    import units_base, spells, ui, hd_res',
             '    w, h, bpp, f = hd_res.Read()',
             '    gamemodule.SetDisplayMode(w, h, bpp // 8, f)',
             '    ui.HD_Init()',
             '']
    return chr(10).join(lines)


def cfg_new(rows):
    # base + config rows; the selected default is the FIRST config row
    base = [[640, 480, 0], [800, 600, 0], [1024, 768, 0], [1280, 960, 0]]
    idx = None
    for (w, h, bpp, f) in rows:
        found = None
        for r in base:
            if r[0] == w and r[1] == h:
                found = r
                break
        if found is None:
            base.append([w, h, 0])
            found = base[-1]
        if idx is None:
            idx = base.index(found)
    base[idx][2] = 1
    lines = ['R_RESOLUTION = ' + repr(base), 'R_BITPERPIXEL = [[16, 0, 0], [32, 0, 1]]',
             'R_MUSIC = 1', 'R_FULLSCREEN = %d' % rows[0][3]]
    return chr(10).join(lines)


