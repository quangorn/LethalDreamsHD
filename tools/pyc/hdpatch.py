def apply_patch(path, old, new, all_replace=False):
    """Идемпотентно: если new уже есть - пропуск; иначе вхождение old (all_replace - все)."""
    s = open(path, encoding='utf-8').read()
    if new in s:
        return 'skip'
    n = s.count(old)
    if all_replace:
        if n == 0:
            return 'FAIL(count=0)'
    elif n != 1:
        return 'FAIL(count=%d)' % n
    s = s.replace(old, new)
    open(path, 'w', encoding='utf-8', newline='\n').write(s)
    return 'ok'


def main():
    fails = []
    rows = read_hd_cfg()
    w0, h0, bpp0, f0 = rows[0]
    print('hd.cfg:', rows, '-> старт %dx%d BPP=%d F=%d' % (w0, h0, bpp0, f0))

    hd_res = os.path.join(BUILD, 'hd_res.py')
    src = hd_res_src(rows)
    open(hd_res, 'w', encoding='utf-8', newline='\n').write(src)
    print('hd_res.py: ROWS =', rows, '(Read() читает hd.cfg в рантайме)')

    GS_NEW = gs_new()
    CFG_NEW = cfg_new(rows)

    ui_path = os.path.join(BUILD, 'ui', 'ui.py')
    r = apply_patch(ui_path, UI_HELPERS_OLD, UI_HELPERS_NEW)
    print('ui helpers:', r)
    if r == 'FAIL(count=%d)' % 0:
        fails.append(('ui helpers', r))
    r = apply_patch(ui_path, UI_INIT_OLD, UI_INIT_NEW)
    print('ui HD_Init:', r)
    for ent in UI_SETS:
        old = ent[0]
        new = ent[1]
        all_replace = len(ent) > 2 and ent[2]
        r = apply_patch(ui_path, old, new, all_replace)
        print('ui', old[:40].strip(), '->', r)
        if r.startswith('FAIL'):
            fails.append((old[:40], r))
    for name in UI_MOUSE:
        old = "    def %s(self, mx, my, flags):\n" % name
        new = "    def %s(self, mx, my, flags):\n        mx = MC(mx)\n        my = MY(my)\n" % name
        r = apply_patch(ui_path, old, new)
        print('ui mouse', name, '->', r)
        if r.startswith('FAIL'):
            fails.append((name, r))

    gs = os.path.join(BUILD, 'gamescript.py')
    r = apply_patch(gs, GS_OLD, GS_NEW)
    print('gamescript:', r)
    if r.startswith('FAIL'):
        fails.append(('gamescript', r))

    cfg = os.path.join(BUILD, 'cfg', 'cfg_default.py')
    r = apply_patch(cfg, CFG_OLD, CFG_NEW)
    print('cfg_default:', r)
    if r.startswith('FAIL'):
        fails.append(('cfg', r))

    gl = os.path.join(BUILD, 'globalscript.py')
    r = apply_patch(gl, GLOB_OLD, GLOB_NEW)
    print('globalscript:', r)
    if r.startswith('FAIL'):
        fails.append(('globalscript', r))

    if fails:
        print('НЕУДАЧИ:', len(fails))
        for f in fails:
            print('  ', f)
        sys.exit(1)


if __name__ == '__main__':
    main()
