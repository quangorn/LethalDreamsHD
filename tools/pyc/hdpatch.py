#!/usr/bin/env python3
"""Адъюстер HD-масштабирования поверх нормализованных .py в build/.

Канвас UI = 1024x768; движок рендерит w x h с масштабом s = w/1024.
Движку передаём координаты e = k*c + dx (по X) и e = k*c (по Y), где
k = h*1024/(w*768), dx = (1024 - 1024k)/2. Мышиные координаты движка
обращаем: c = (m - dx)/k по X и c = m/k по Y.
При 1920x1440 k = 1, dx = 0: правки эквивалентны оригиналу.

Применяется к build/*.py (каталог в корне репозитория); идемпотентен (повторное
применение не меняет файл). Файл лежит в tools/pyc/, hd.cfg - в корне репозитория.
"""
import os, sys

